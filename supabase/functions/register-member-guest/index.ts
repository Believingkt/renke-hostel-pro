import { createClient } from "https://esm.sh/@supabase/supabase-js@2.76.1";
import { buildCorsHeaders } from "../_shared/cors.ts";

function randomPassword(length = 24): string {
  const chars = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789!@#$%";
  const buf = new Uint8Array(length);
  crypto.getRandomValues(buf);
  let out = "";
  for (let i = 0; i < length; i++) out += chars.charAt(buf[i] % chars.length);
  return out;
}

Deno.serve(async (req) => {
  const corsHeaders = buildCorsHeaders(req);
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const body = await req.json();
    const email = String(body.email || "").trim().toLowerCase();
    const name = (body.name ? String(body.name).trim() : "").slice(0, 100);
    const phone = (body.phone ? String(body.phone).trim() : "").slice(0, 30);
    let password: string = body.password ? String(body.password) : "";

    if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      return new Response(JSON.stringify({ error: "invalid_email" }), {
        status: 400, headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const autoGenerated = !password;
    if (autoGenerated) password = randomPassword(24);

    const admin = createClient(
      Deno.env.get("SUPABASE_URL")!,
      Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!,
      { auth: { autoRefreshToken: false, persistSession: false } }
    );

    // Reject if already exists
    const { data: existing } = await admin
      .from("platform_members")
      .select("id, user_id")
      .ilike("email", email)
      .maybeSingle();
    if (existing) {
      return new Response(JSON.stringify({ error: "email_exists", member_id: existing.user_id }), {
        status: 409, headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    // Create auth user (email_confirm=false so confirmation email is sent)
    const { data: created, error: createErr } = await admin.auth.admin.createUser({
      email,
      password,
      email_confirm: false,
      user_metadata: { name: name || email.split("@")[0], phone },
    });
    if (createErr || !created?.user) {
      return new Response(JSON.stringify({ error: createErr?.message || "create_failed" }), {
        status: 400, headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const userId = created.user.id;

    // Insert platform_members
    const { error: memberErr } = await admin
      .from("platform_members")
      .insert({
        user_id: userId,
        email,
        name: name || email.split("@")[0],
        phone: phone || null,
      });
    if (memberErr) {
      console.error("platform_members insert failed:", memberErr.message);
    }

    // Trigger verification email via anon signUp resend (createUser doesn't send)
    try {
      const anon = createClient(
        Deno.env.get("SUPABASE_URL")!,
        Deno.env.get("SUPABASE_ANON_KEY")!,
      );
      await anon.auth.resend({ type: "signup", email });
    } catch (e) {
      console.error("resend confirmation failed:", (e as Error).message);
    }

    return new Response(JSON.stringify({
      success: true,
      member_id: userId,
      auto_generated_password: autoGenerated,
    }), {
      status: 200, headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (e: any) {
    return new Response(JSON.stringify({ error: e.message || "server_error" }), {
      status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
