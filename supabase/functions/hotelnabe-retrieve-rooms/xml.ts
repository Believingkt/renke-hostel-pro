// HotelNabe outbound "retrieveRoomOnly" — Request builder + Response parser
// Direction: 人客多 (PMS) → HotelNabe
// Independent module; do NOT reuse owlting-* code.

// @ts-ignore esm.sh resolves fast-xml-parser for Deno
import { XMLParser, XMLBuilder } from "https://esm.sh/fast-xml-parser@4.4.1";

const NS = "http://www.opentravel.org/OTA/2003/05";

export interface BuildAvailRQInput {
  echoToken: string;
  hotelCode: string;
  requestorId: string;       // HOTELNABE_INBOUND_ID
  password: string;          // HOTELNABE_INBOUND_PASSWORD
  pmsName: string;           // HOTELNABE_PMS_ID (e.g. "11")
  timeStamp?: string;        // ISO; default now
  version?: string;          // default "1.0"
}

/**
 * Build OTA_HotelAvailRQ for HotelNabe `retrieveRoomOnly` endpoint.
 *
 * Per HotelNabe Connection V1.0.1: AvailRQ EchoToken is generated by PMS side.
 * RequestorID Type=18 (PMS), @Name is the PMS identifier provided by HotelNabe.
 */
export function buildHotelnabeAvailRQ(input: BuildAvailRQInput): string {
  const ts = input.timeStamp ?? new Date().toISOString();
  const ver = input.version ?? "1.0";
  const builder = new XMLBuilder({
    ignoreAttributes: false,
    attributeNamePrefix: "@_",
    suppressEmptyNode: true,
    format: false,
  });
  const doc = {
    OTA_HotelAvailRQ: {
      "@_xmlns": NS,
      "@_EchoToken": input.echoToken,
      "@_Version": ver,
      "@_TimeStamp": ts,
      POS: {
        Source: {
          RequestorID: {
            "@_Type": "18",
            "@_ID": input.requestorId,
            "@_MessagePassword": input.password,
            "@_Name": input.pmsName,
          },
        },
      },
      AvailRequestSegments: {
        AvailRequestSegment: {
          HotelSearchCriteria: {
            Criterion: {
              HotelRef: { "@_HotelCode": input.hotelCode },
            },
          },
        },
      },
    },
  };
  return `<?xml version="1.0" encoding="UTF-8"?>` + builder.build(doc);
}

export interface ParsedRSRoomType {
  roomId: string | null;        // HotelNabe room type ID
  roomTypeCode: string | null;  // PMS-side numeric code
}

export interface ParsedAvailRS {
  echoToken: string | null;
  success: boolean;
  errors: { type: string | null; code: string | null; message: string }[];
  rooms: ParsedRSRoomType[];
}

const parser = new XMLParser({
  ignoreAttributes: false,
  attributeNamePrefix: "@_",
  textNodeName: "#text",
  trimValues: true,
  parseAttributeValue: false,
  removeNSPrefix: true,
  isArray: (name) => ["RoomStay", "RoomType", "RatePlan", "Error"].includes(name),
});

function asArr<T>(v: T | T[] | undefined | null): T[] {
  if (v == null) return [];
  return Array.isArray(v) ? v : [v];
}

export function parseHotelnabeAvailRS(xml: string): ParsedAvailRS {
  const doc = parser.parse(xml);
  const rs = doc?.OTA_HotelAvailRS;
  if (!rs) {
    return { echoToken: null, success: false, errors: [{ type: null, code: null, message: "Missing OTA_HotelAvailRS root" }], rooms: [] };
  }
  const echoToken = rs["@_EchoToken"] ? String(rs["@_EchoToken"]) : null;
  const success = rs.Success !== undefined && rs.Errors === undefined;
  const errors = asArr(rs?.Errors?.Error).map((e: any) => ({
    type: e?.["@_Type"] ? String(e["@_Type"]) : null,
    code: e?.["@_Code"] ? String(e["@_Code"]) : null,
    message: String(e?.["#text"] ?? e?.["@_ShortText"] ?? "").trim(),
  }));

  const rooms: ParsedRSRoomType[] = [];
  const stays = asArr(rs?.RoomStays?.RoomStay);
  for (const stay of stays) {
    const rts = asArr(stay?.RoomTypes?.RoomType);
    for (const rt of rts) {
      const roomId = rt?.["@_RoomID"] != null ? String(rt["@_RoomID"]) : null;
      const roomTypeCode = rt?.["@_RoomTypeCode"] != null ? String(rt["@_RoomTypeCode"]) : null;
      if (roomId || roomTypeCode) rooms.push({ roomId, roomTypeCode });
    }
  }
  return { echoToken, success: success || errors.length === 0, errors, rooms };
}

// ─── Mapping report ─────────────────────────────────────────────────

export interface OurRoomType {
  id: string;
  name: string;
  numeric_code: number | null;
}

export interface MappingReport {
  matched: {
    hotelnabe_room_id: string | null;
    hotelnabe_room_type_code: string;
    our_room_type_id: string;
    our_room_type_name: string;
  }[];
  mismatch: {
    hotelnabe_room_id: string | null;
    hotelnabe_room_type_code: string | null;
    reason: string;
  }[];
  missing_on_our_side: {
    hotelnabe_room_id: string | null;
    hotelnabe_room_type_code: string;
  }[];
  unused_on_our_side: {
    our_room_type_id: string;
    our_room_type_name: string;
    numeric_code: number;
  }[];
  totals: { remote: number; ours: number; matched: number; missing: number; mismatch: number; unused: number };
}

/**
 * Compare HotelNabe-returned room types with our `room_types.numeric_code` per accommodation.
 *
 * - matched: numeric_code 對得上
 * - mismatch: HotelNabe 回傳缺 RoomTypeCode 或非數字
 * - missing_on_our_side: 旭海有，我方查無 numeric_code
 * - unused_on_our_side: 我方有 numeric_code 但旭海未回傳
 */
export function buildMappingReport(remoteRooms: ParsedRSRoomType[], ourRooms: OurRoomType[]): MappingReport {
  const ourByCode = new Map<number, OurRoomType>();
  for (const r of ourRooms) if (r.numeric_code != null) ourByCode.set(Number(r.numeric_code), r);

  const matched: MappingReport["matched"] = [];
  const mismatch: MappingReport["mismatch"] = [];
  const missing: MappingReport["missing_on_our_side"] = [];
  const seenCodes = new Set<number>();

  for (const rr of remoteRooms) {
    if (!rr.roomTypeCode || !/^-?\d+$/.test(rr.roomTypeCode)) {
      mismatch.push({
        hotelnabe_room_id: rr.roomId,
        hotelnabe_room_type_code: rr.roomTypeCode,
        reason: "missing or non-numeric RoomTypeCode",
      });
      continue;
    }
    const code = Number(rr.roomTypeCode);
    const ours = ourByCode.get(code);
    if (ours) {
      matched.push({
        hotelnabe_room_id: rr.roomId,
        hotelnabe_room_type_code: rr.roomTypeCode,
        our_room_type_id: ours.id,
        our_room_type_name: ours.name,
      });
      seenCodes.add(code);
    } else {
      missing.push({ hotelnabe_room_id: rr.roomId, hotelnabe_room_type_code: rr.roomTypeCode });
    }
  }

  const unused: MappingReport["unused_on_our_side"] = [];
  for (const [code, r] of ourByCode.entries()) {
    if (!seenCodes.has(code)) unused.push({ our_room_type_id: r.id, our_room_type_name: r.name, numeric_code: code });
  }

  return {
    matched,
    mismatch,
    missing_on_our_side: missing,
    unused_on_our_side: unused,
    totals: {
      remote: remoteRooms.length,
      ours: ourRooms.filter(r => r.numeric_code != null).length,
      matched: matched.length,
      missing: missing.length,
      mismatch: mismatch.length,
      unused: unused.length,
    },
  };
}

/** Mask MessagePassword attribute in raw XML before persisting for audit. */
export function maskPasswordInXml(xml: string): string {
  return xml.replace(/(MessagePassword\s*=\s*")([^"]*)(")/gi, (_m, p1, _v, p3) => `${p1}***${p3}`);
}
